import assert from 'node:assert/strict';
import {ownedVolumeUsage,conservativeCapacity} from './accounting.mjs';
let passed=0;const test=(name,fn)=>{fn();passed++;console.log(JSON.stringify({name,passed:true}));};
const p='/owned/project';
const v=(name,size,project=p)=>({Name:name,Labels:{'buildctl.project':project},UsageData:{Size:size}});
test('exact owned bytes; unrelated excluded',()=>assert.deepEqual(ownedVolumeUsage({Volumes:[v('a',50),v('b',7),v('other',100000,'/other')]},p),{bytes:57,count:2}));
test('missing inventory refuses',()=>assert.throws(()=>ownedVolumeUsage({},p)));
test('missing size refuses',()=>assert.throws(()=>ownedVolumeUsage({Volumes:[v('a',undefined)]},p)));
test('negative size refuses',()=>assert.throws(()=>ownedVolumeUsage({Volumes:[v('a',-1)]},p)));
test('fractional size refuses',()=>assert.throws(()=>ownedVolumeUsage({Volumes:[v('a',1.5)]},p)));
test('duplicate owned identity refuses',()=>assert.throws(()=>ownedVolumeUsage({Volumes:[v('a',1),v('a',1)]},p)));
test('sum overflow refuses',()=>assert.throws(()=>ownedVolumeUsage({Volumes:[v('a',Number.MAX_SAFE_INTEGER),v('b',1)]},p)));
test('unlabelled unrelated data excluded',()=>assert.deepEqual(ownedVolumeUsage({Volumes:[{Name:'other',UsageData:{Size:-1}}]},p),{bytes:0,count:0}));
let disks=new Map([[1,1000],[2,2000]]),volumes={bytes:50};
const free=conservativeCapacity(()=>new Map(disks),()=>({...volumes}));
test('same initial physical minimum',()=>assert.equal(free(),1000));
test('nonminimum filesystem growth charged',()=>{disks.set(2,1900);assert.equal(free(),900);});
test('preallocated Docker data charged',()=>{volumes.bytes=80;assert.equal(free(),870);});
test('host and Docker growth conservatively double charged',()=>{disks.set(1,900);assert.equal(free(),770);});
test('another disk freeing space cannot mask growth',()=>{disks.set(2,2100);assert.equal(free(),870);});
test('volume decrease cannot mask host growth',()=>{volumes.bytes=40;assert.equal(free(),900);});
test('changed filesystem identity refuses',()=>{disks.set(3,3000);assert.throws(free);disks.delete(3);});
test('unknown capacity refuses',()=>{disks.set(1,NaN);assert.throws(free);});
test('Docker query failure refuses',()=>assert.throws(conservativeCapacity(()=>new Map([[1,1000]]),()=>{throw Error('metadata unavailable')})));
console.log(JSON.stringify({controlsPassed:passed,limitsRelaxed:false,installedGuardChanged:false}));

"""Generate public constant data from Rust, checking the independently pinned API."""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NODE = Path('/Users/admin/.nvm/versions/node/v22.16.0/bin/node')
parser = argparse.ArgumentParser()
parser.add_argument('--write', action='store_true')
args = parser.parse_args()
oracle = ROOT / json.loads((ROOT / '.tools/parity/oracles/current.json').read_text())['source']
supplement = json.loads((ROOT / 'fixtures/parity/supplement.json').read_text())
for item in supplement['referenceTree']:
    raw = (oracle / item['path']).read_bytes()
    assert hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest() == item['gitBlob']
native = json.loads(subprocess.check_output([ROOT / 'target/debug/patamaps', 'sssom', 'json', 'profile'], input=b'{}'))
reference = json.loads(subprocess.check_output([NODE, '--input-type=module', '-e', '''
import {pathToFileURL} from 'node:url';
const module = await import(pathToFileURL(process.argv[1]));
process.stdout.write(JSON.stringify({prefixes:module.SSSOM_BUILTIN_PREFIXES,propagatableSlots:module.SSSOM_PROPAGATABLE_SLOTS}));
''', oracle / 'dist/sssom.js']))
assert native == reference, 'Native profile values or propagated-slot order differ from the pinned public API'
# Preserve the public object's observed key order, independently of canonical
# wire ordering. Values and slot ordering are supplied by the Rust engine.
prefixes = {key: native['prefixes'][key] for key in reference['prefixes']}
encoded = ('// Generated by scripts/parity/sssom_profile.py; do not edit.\n'
           'export const SSSOM_BUILTIN_PREFIXES = Object.freeze(' + json.dumps(prefixes, ensure_ascii=False, indent=2) + ');\n'
           'export const SSSOM_PROPAGATABLE_SLOTS = Object.freeze(' + json.dumps(native['propagatableSlots'], ensure_ascii=False, indent=2) + ');\n')
path = ROOT / 'sdk/typescript/sssom-profile.mjs'
if args.write:
    path.write_text(encoded)
else:
    assert path.read_text() == encoded, 'Public profile data is stale; regenerate explicitly'
print(json.dumps({'status': 'generated-and-verified' if args.write else 'verified',
                  'prefixes': len(prefixes), 'propagatableSlots': len(native['propagatableSlots']),
                  'digest': 'sha256:' + hashlib.sha256(encoded.encode()).hexdigest()}))
